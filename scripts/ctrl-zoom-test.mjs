import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: 'new', args: ['--no-sandbox','--disable-gpu'], defaultViewport: { width: 1440, height: 900 } })
const p = await b.newPage()
await p.goto('http://127.0.0.1:4317/', { waitUntil: 'networkidle2' })
await p.evaluate(() => localStorage.setItem('dt:seenWelcome','1'))
const id = await p.evaluate(async () => { const st = await (await fetch('/api/state')).json(); return st.docs.find(d => d.kind === 'pdf')?.id })
await p.goto('http://127.0.0.1:4317/?doc=' + id, { waitUntil: 'networkidle2' })
await new Promise(r => setTimeout(r, 1200))
const read = () => p.evaluate(() => ({ label: document.querySelector('#zoom-label').textContent, pagesZoom: document.querySelector('#pages').style.zoom }))
const before = await read()
await p.keyboard.down('Control'); await p.keyboard.press('Equal'); await p.keyboard.up('Control')
await new Promise(r => setTimeout(r, 400))
const plus = await read()
await p.keyboard.down('Control'); await p.keyboard.press('Minus'); await p.keyboard.press('Minus'); await p.keyboard.up('Control')
await new Promise(r => setTimeout(r, 400))
const minus = await read()
await p.keyboard.down('Control'); await p.keyboard.press('Digit0'); await p.keyboard.up('Control')
await new Promise(r => setTimeout(r, 400))
const reset = await read()
console.log(JSON.stringify({ before, plus, minus, reset }))
await b.close()
