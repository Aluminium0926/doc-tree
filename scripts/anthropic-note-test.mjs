import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: 'new', args: ['--no-sandbox','--disable-gpu'], defaultViewport: { width: 1440, height: 900 } })
const p = await b.newPage()
await p.goto('http://127.0.0.1:4317/', { waitUntil: 'networkidle2' })
await p.evaluate(() => localStorage.setItem('dt:seenWelcome','1'))
await p.reload({ waitUntil: 'networkidle2' })
await new Promise(r => setTimeout(r, 500))
await p.click('#btn-settings')
await new Promise(r => setTimeout(r, 300))
const before = await p.evaluate(() => !document.querySelector('#anthropic-note').hidden)
await p.select('#cfg-format', 'anthropic')
await new Promise(r => setTimeout(r, 200))
const after = await p.evaluate(() => ({ visible: !document.querySelector('#anthropic-note').hidden, text: document.querySelector('#anthropic-note').innerText.slice(0,60) }))
await p.screenshot({ path: 'anthropic-note.png', clip: { x: 470, y: 200, width: 520, height: 330 } })
await p.select('#cfg-format', 'openai')
await new Promise(r => setTimeout(r, 200))
const back = await p.evaluate(() => !document.querySelector('#anthropic-note').hidden)
console.log(JSON.stringify({ before, after, back }))
await b.close()
