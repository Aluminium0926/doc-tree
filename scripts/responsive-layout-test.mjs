import puppeteer from 'puppeteer-core'
const desk=await puppeteer.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:'new',args:['--no-sandbox','--disable-gpu'],defaultViewport:{width:872,height:900}})
const p=await desk.newPage()
await p.goto('http://127.0.0.1:4317/',{waitUntil:'networkidle2'})
await p.evaluate(()=>{localStorage.removeItem('dt:left');localStorage.setItem('dt:seenWelcome','1')})
await p.reload({waitUntil:'networkidle2'});await new Promise(r=>setTimeout(r,700))
await p.screenshot({path:'narrow-desktop.png'})
const deskState=await p.evaluate(()=>({collapsed:document.querySelector('#app').classList.contains('collapsed'),btn:getComputedStyle(document.querySelector('#btn-sidebar')).display}))
await desk.close()

const mob=await puppeteer.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:'new',args:['--no-sandbox','--disable-gpu'],defaultViewport:{width:390,height:844,isMobile:true,hasTouch:true}})
const m=await mob.newPage()
