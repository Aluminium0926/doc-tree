import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: 'new', args: ['--no-sandbox','--disable-gpu'], defaultViewport: { width: 1440, height: 900 } })
const p = await b.newPage()
await p.goto('http://127.0.0.1:4317/', { waitUntil: 'networkidle2' })
await p.evaluate(() => localStorage.setItem('dt:seenWelcome','1'))
const id = await p.evaluate(async () => { const st = await (await fetch('/api/state')).json(); return st.docs.find(d => d.kind === 'pdf')?.id })
await p.goto('http://127.0.0.1:4317/?doc=' + id, { waitUntil: 'networkidle2' })
await p.waitForSelector('.page', { timeout: 20000 })
await new Promise(r => setTimeout(r, 1000))
const box = await p.evaluate(() => { const el = document.querySelector('.page'); const r = el.getBoundingClientRect(); return { x: r.x + r.width/2, y: r.y + 200 } })
await p.mouse.click(box.x, box.y, { button: 'right' })
await new Promise(r => setTimeout(r, 300))
const m = await p.evaluate(() => { const el = document.querySelector('#page-menu'); const r = el.getBoundingClientRect(); return { visible: !el.hidden, w: Math.round(r.width), h: Math.round(r.height), rect: { x: Math.round(r.x), y: Math.round(r.y) } } })
console.log(JSON.stringify(m))
await p.screenshot({ path: 'page-menu2.png', clip: { x: m.rect.x - 30, y: m.rect.y - 30, width: m.w + 60, height: m.h + 60 } })
await b.close()
