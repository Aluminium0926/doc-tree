import puppeteer from 'puppeteer-core'
const b=await puppeteer.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:'new',args:['--no-sandbox','--disable-gpu'],defaultViewport:{width:1400,height:950}})
const p=await b.newPage()
await p.goto('http://127.0.0.1:4317/',{waitUntil:'networkidle2'})
await p.evaluate(()=>localStorage.setItem('dt:seenWelcome','1'))
await p.reload({waitUntil:'networkidle2'});await new Promise(r=>setTimeout(r,900))
const docs=await p.evaluate(async()=>(await (await fetch('/api/state')).json()).docs)
const pdf=docs.find(d=>d.kind==='pdf')
await p.evaluate((t)=>{[...document.querySelectorAll('.doc-item')].find(x=>x.textContent.includes(t))?.click()},pdf.title)
await new Promise(r=>setTimeout(r,2500))
await p.evaluate(()=>{const sc=document.querySelector('#page-scroll');sc.scrollTop=Math.round(sc.scrollHeight*0.4)})
await new Promise(r=>setTimeout(r,700))
const before=await p.evaluate(()=>({scroll:document.querySelector('#page-scroll').scrollTop,views:JSON.parse(localStorage.getItem('dt:views')||'{}')}))
console.log('before',before.scroll,JSON.stringify(before.views[pdf.id]))
// switch to another doc then back
const other=docs.find(d=>d.id!==pdf.id)
await p.evaluate((t)=>{[...document.querySelectorAll('.doc-item')].find(x=>x.textContent.includes(t))?.click()},other.title)
await new Promise(r=>setTimeout(r,1500))
const mid=await p.evaluate(()=>({views:JSON.parse(localStorage.getItem('dt:views')||'{}')}))
console.log('saved old',JSON.stringify(mid.views[pdf.id]))
await p.evaluate((t)=>{[...document.querySelectorAll('.doc-item')].find(x=>x.textContent.includes(t))?.click()},pdf.title)
await new Promise(r=>setTimeout(r,600))
const t0=await p.evaluate(()=>({scroll:document.querySelector('#page-scroll').scrollTop,views:JSON.parse(localStorage.getItem('dt:views')||'{}')[JSON.parse(localStorage.getItem('dt:views')||'{}')&&Object.keys(JSON.parse(localStorage.getItem('dt:views')||'{}'))[0]]}))
await new Promise(r=>setTimeout(r,2500))
const after=await p.evaluate(()=>({scroll:document.querySelector('#page-scroll').scrollTop}))
console.log('after immediate',t0.scroll,'after 2.5s',after.scroll)
await b.close()
